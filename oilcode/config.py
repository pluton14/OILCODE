def require_data_files() -> None:
    """Проверить, что все файлы данных на месте, и сразу сказать, чего не хватает.

    Без этой проверки первый запуск падает трейсбеком pandas в глубине
    loaders.py — непонятно, что вообще случилось. Вызывается в run_demo.py
    до создания оркестратора, чтобы упасть сразу и ясно.
    """
    missing = [(path, desc) for path, desc in REQUIRED_DATA_FILES.items()
              if not path.exists()]
    if not missing:
        return

    lines = [
        "",
        "Не найдены файлы данных хакатона — их нет в репозитории специально",
        "(см. .gitignore), каждый участник кладёт их к себе локально.",
        "",
        f"Положите файлы организаторов в {DOCS}:",
    ]
    for path, desc in missing:
        try:
            rel = path.relative_to(ROOT)
        except ValueError:
            rel = path
        lines.append(f"  ✗ {rel}   — {desc}")
    lines += [
        "",
        "Структура и назначение файлов описаны в README.md, раздел «Данные».",
    ]
    raise SystemExit("\n".join(lines))

